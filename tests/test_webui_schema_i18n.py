"""The schema's OWN prose (``desc:`` / ``example:``) — parsed, rendered, and translated.

A schema author writes a description once, beside the field it explains, and the console shows it in
the reader's language. Two halves:

* the RENDER half: ``configgen`` reads ``desc``/``example`` into the field model, and the shared
  config editor shows the description as a tooltip beside the key (never a clipped line that grows
  the row) and the example as the control's PLACEHOLDER while the field is empty;
* the TRANSLATION half: the descriptions are DATA, so Babel cannot extract them from YAML — they get
  the ``schema`` catalog domain, generated by ``services.webservice.schema_i18n`` from the schemas
  themselves, and looked up per render through the environment's ``schema_text`` global.

Pinned here: the parsing (leaf, block, sequence element), the picker showing the description instead
of the bare kind word, the tooltip + placeholder markup, the escaping of schema text, the language
binding, the generator's merge rules (keep / fuzzy / obsolete / identity for English) and the
runtime's fallback to the schema's own text when a language has no entry.
"""
from __future__ import annotations

import pathlib
import re

import pytest

from services.webservice import configgen, i18n, schema_i18n, templating

SCHEMA = """\
type: map
nullable: false
desc: The whole file.
mapping:
  port:
    type: int
    nullable: false
    range: {min: 1, max: 65535}
    desc: The UDP port the server listens on.
    example: "1308"
  rows:
    type: seq
    nullable: false
    desc: One entry per row.
    sequence:
      - type: map
        nullable: false
        mapping:
          n:
            type: int
            nullable: true
            desc: A number.
            example: "42"
  optional_block:
    type: map
    nullable: true
    desc: A block nobody has to fill.
    mapping:
      x: {type: str, nullable: true}
"""


@pytest.fixture
def tree(tmp_path):
    """The field model of :data:`SCHEMA` — what the editor renders from."""
    path = tmp_path / "s.yaml"
    path.write_text(SCHEMA, encoding="utf-8")
    return configgen.describe(configgen.load_schema(path))


def _field(root, *keys):
    node = root
    for key in keys:
        node = next(child for child in node.children if child.key == key)
    return node


# --------------------------------------------------------------- 1. the model reads the prose

def test_a_leaf_carries_its_description_and_its_example(tree):
    port = _field(tree, "port")
    assert port.desc == "The UDP port the server listens on."
    assert port.example == "1308"


def test_a_block_and_a_sequence_element_carry_theirs_too(tree):
    rows = _field(tree, "rows")
    assert rows.desc == "One entry per row."
    # a sequence's element is a field of its own: the description on the inner rule is kept
    assert rows.element is not None
    n = rows.element.children[0]
    assert n.key == "n" and n.desc == "A number." and n.example == "42"


def test_a_field_without_prose_carries_nothing(tree):
    """The old behaviour, unchanged: no ``desc`` means the kind word is the only description."""
    assert _field(tree, "optional_block", "x").desc == ""
    assert _field(tree, "optional_block", "x").example is None


def test_the_picker_offers_the_description_not_the_kind_word(tree):
    """A ``+ Add`` choice reads as a sentence when the schema has one — the kind word otherwise."""
    options = {option["key"]: option for option in configgen.hidden_options(tree, tree.children, {})}
    assert options["optional_block"]["desc"] == "A block nobody has to fill."
    assert options["optional_block"]["kind"]                     # the kind word is still carried


# --------------------------------------------------------------- 2. the editor renders them

@pytest.mark.asyncio
async def test_the_main_editor_shows_the_schema_prose(tmp_path):
    from conftest import asgi_client
    from services.webservice.pages import settings as settings_page
    from test_webui_dashboard import BOT_YAML, _build, _hash, _login

    (tmp_path / "services").mkdir()
    (tmp_path / "services" / "bot.yaml").write_text(BOT_YAML, encoding="utf-8")
    # guild_id is MANDATORY and carries an example, so omitting it still renders the control — which
    # is exactly the state an empty field with an example is in.
    (tmp_path / "main.yaml").write_text("language: en\n", encoding="utf-8")
    app, _ = _build(tmp_path, users=[{"username": "staff", "password_hash": _hash(),
                                      "roles": ["Admin"]}])
    async with asgi_client(app) as client:
        await _login(client, "staff")
        response = await client.get(settings_page.SETTINGS_MAIN_PATH)
    assert response.status_code == 200, response.text[:300]
    page = response.text
    # the ROW prints the sentence ITSELF (in the reader's language), so nothing has to be hovered
    assert '<span class="desc">Discord guild/server ID where the bot is installed.</span>' in page
    # ...and the grey line that used to repeat the field's own key is gone
    assert '<span class="key">guild_id</span>' not in page, "the duplicated key line is gone"
    # ...as is the row's ⓘ: it would offer by hover what the row already says
    row = page.split('<div class="nm">guild_id</div>', 1)[1][:800]
    assert "cfg-info" not in row, "the row needs no hover marker"
    # a BLOCK keeps its ⓘ (a sentence would stretch the summary line)
    assert 'Database connection and pooling configuration.' in page
    # the example rides the control as a placeholder (the field is empty in this file)
    assert 'placeholder="112233445566778899"' in page


def test_the_second_line_shows_the_path_only_when_there_is_no_description(tmp_path):
    """The rule of the row's second line, at the macro's own level:

    * the schema's sentence is printed whenever the field has one;
    * a NESTED field ALSO prints its path — the context the bold leaf key does not carry, and what the
      operator would search the file for;
    * a field whose relative key IS the bold key prints it never: that is the duplicate the sentence
      replaced, and it is the case that made the row read twice.
    """
    path = tmp_path / "s.yaml"
    path.write_text("""\
type: map
nullable: false
mapping:
  guild_id:
    type: int
    nullable: false
  database:
    type: map
    nullable: false
    mapping:
      url:
        type: str
        nullable: true
        desc: The connection string.
      host:
        type: str
        nullable: true
""", encoding="utf-8")
    tree = configgen.describe(configgen.load_schema(path))
    guild_id = _field(tree, "guild_id")
    url = _field(tree, "database", "url")
    host = _field(tree, "database", "host")

    environment = templating.build_environment()
    template = environment.from_string(
        '{% import "_scope_fields.html" as sf %}{{ sf.row(f, values, displays) }}')
    render = lambda f: template.render(f=f, values={}, displays={})   # noqa: E731

    assert '<span class="key">database.host</span>' in render(host), "the path is the context"
    url_html = render(url)
    assert "The connection string." in url_html, "the schema's sentence is printed"
    assert '<span class="key">database.url</span>' in url_html, \
        "and the path stays: it is context, not the duplicate the sentence replaced"
    quiet = render(guild_id)
    assert '<div class="nm">guild_id</div>' in quiet
    assert '<span class="key">' not in quiet and '<span class="desc">' not in quiet, \
        "nothing to say on the second line: no duplicate, no sentence"


def test_the_ordinary_editor_prints_the_sentence_in_the_row(tmp_path):
    """The OTHER editor (the plain form) says the same thing the same way — no hover marker."""
    path = tmp_path / "s.yaml"
    path.write_text("""\
type: map
nullable: false
mapping:
  port:
    type: int
    nullable: false
    desc: The UDP port the server listens on.
""", encoding="utf-8")
    field = _field(configgen.describe(configgen.load_schema(path)), "port")
    environment = templating.build_environment()
    template = environment.from_string(
        '{% import "_config_fields.html" as cf %}'
        '{{ cf.render_field(f, values, rows, customs, elements, choices, sections=sections, '
        'hidden=hidden, picks=picks, removable=removable) }}')
    rendered = template.render(f=field, values={}, rows={}, customs={}, elements={}, choices={},
                               sections={}, hidden=[], picks={}, removable=[])
    assert '<span class="cfg-desc">The UDP port the server listens on.</span>' in rendered
    assert "cfg-info" not in rendered, "the row prints the sentence, it does not hide it"


def test_the_description_tooltip_escapes_hostile_schema_text():
    """Schema text is DATA: it goes through the environment's autoescape like any other value."""
    environment = templating.build_environment()
    template = environment.from_string(
        '{% import "_config_fields.html" as cf %}{{ cf.schema_info(desc, "v1") }}')
    rendered = template.render(desc='<script>alert(1)</script> " onmouseover="x')
    assert "<script>" not in rendered
    assert "&lt;script&gt;" in rendered
    assert 'onmouseover="x"' not in rendered          # the quote was escaped, not left as markup


def test_the_description_follows_the_environments_language(monkeypatch, tmp_path):
    """A per-language environment looks the description up in ITS OWN catalog (never another's)."""
    babel = pytest.importorskip("babel")                        # noqa: F841 - tooling dependency
    from babel.messages.catalog import Catalog
    from babel.messages.mofile import write_mo

    # a language code of its own, so no earlier test's cached translator can answer for it
    language = "zz"
    directory = tmp_path / language / "LC_MESSAGES"
    directory.mkdir(parents=True)
    catalog = Catalog(locale=language, domain=i18n.SCHEMA_DOMAIN)
    catalog.add("The UDP port the server listens on.", string="DER UDP-PORT")
    with (directory / "schema.mo").open("wb") as handle:
        write_mo(handle, catalog)

    monkeypatch.setattr(i18n, "LOCALE_DIR", tmp_path)
    monkeypatch.setattr(i18n, "_SCHEMA_TRANSLATORS", {})

    translated = templating.build_environment(language=language).from_string(
        '{% import "_config_fields.html" as cf %}{{ cf.schema_info(desc, "v1") }}')
    assert "DER UDP-PORT" in translated.render(desc="The UDP port the server listens on.")
    # and the SAME description in an unbound environment stays the schema's own English
    plain = templating.build_environment().from_string(
        '{% import "_config_fields.html" as cf %}{{ cf.schema_info(desc, "v1") }}')
    assert "DER UDP-PORT" not in plain.render(desc="The UDP port the server listens on.")


# --------------------------------------------------------------- 3. the generator

@pytest.fixture
def project(monkeypatch, tmp_path):
    """A throwaway repository: one schema folder and an empty ``locale/``."""
    (tmp_path / "schemas").mkdir()
    (tmp_path / "locale").mkdir()
    monkeypatch.setattr(schema_i18n, "REPO_ROOT", tmp_path)
    monkeypatch.setattr(schema_i18n, "LOCALE_DIR", tmp_path / "locale")
    return tmp_path


def _write_schema(project: pathlib.Path, text: str) -> pathlib.Path:
    path = project / "schemas" / "main_schema.yaml"
    path.write_text(text, encoding="utf-8")
    return path


def test_the_generator_finds_every_description_with_its_field_path(project):
    _write_schema(project, SCHEMA)
    entries = {entry["text"]: entry for entry in schema_i18n.collect()}
    assert set(entries) == {"The whole file.", "The UDP port the server listens on.",
                            "One entry per row.", "A number.", "A block nobody has to fill."}
    # the ``#.`` comment names the FIELD, never the rule keywords that carry it
    assert entries["The UDP port the server listens on."]["comments"] == ["main_schema:port"]
    assert entries["A number."]["comments"] == ["main_schema:rows.[0].n"]
    assert entries["The UDP port the server listens on."]["locations"][0][0] == "schemas/main_schema.yaml"


def test_the_generator_keeps_an_existing_translation(project):
    _write_schema(project, SCHEMA)
    path = schema_i18n.write_catalog(schema_i18n.merge(schema_i18n.collect(), "de")[0], "de")
    text = path.read_text(encoding="utf-8")
    text = text.replace(
        'msgid "The UDP port the server listens on."\nmsgstr ""',
        'msgid "The UDP port the server listens on."\nmsgstr "DER UDP-PORT"')
    path.write_text(text, encoding="utf-8")

    catalog, counts = schema_i18n.merge(schema_i18n.collect(), "de")
    assert counts["added"] == 0, "nothing is new: the same descriptions were found again"
    entry = next(m for m in catalog if m.id == "The UDP port the server listens on.")
    assert entry.string == "DER UDP-PORT", "a re-run must never lose a translation"


def test_a_rewritten_description_is_carried_over_as_fuzzy(project):
    _write_schema(project, SCHEMA)
    path = schema_i18n.write_catalog(schema_i18n.merge(schema_i18n.collect(), "de")[0], "de")
    text = path.read_text(encoding="utf-8").replace(
        'msgid "The UDP port the server listens on."\nmsgstr ""',
        'msgid "The UDP port the server listens on."\nmsgstr "DER UDP-PORT"')
    path.write_text(text, encoding="utf-8")

    # the author rewrites the sentence in place: same field, new wording
    _write_schema(project, SCHEMA.replace("The UDP port the server listens on.",
                                          "The UDP port the server listens on (changed)."))
    catalog, counts = schema_i18n.merge(schema_i18n.collect(), "de")
    assert counts["fuzzy"] == 1 and counts["added"] == 0, \
        "a rewritten sentence needs REVIEW, not a brand-new entry"
    ids = {str(message.id) for message in catalog if message.id}
    assert "The UDP port the server listens on." not in ids, "the old wording leaves the catalog"
    reviewed = next(m for m in catalog if m.id == "The UDP port the server listens on (changed).")
    assert reviewed.string == "DER UDP-PORT", "the old translation is CARRIED OVER, never lost"
    assert reviewed.fuzzy, "marked fuzzy, so it is not served until a human reviews it"


def test_english_is_filled_in_as_the_identity(project):
    _write_schema(project, SCHEMA)
    catalog, _ = schema_i18n.merge(schema_i18n.collect(), "en")
    entry = next(m for m in catalog if m.id == "One entry per row.")
    assert entry.string == "One entry per row."


def test_check_reports_an_out_of_date_catalog_and_then_passes(project, capsys):
    _write_schema(project, SCHEMA)
    assert schema_i18n.main(["--check", "--langs", "en"]) == 1, "nothing generated yet = out of date"
    assert "OUT OF DATE" in capsys.readouterr().out

    assert schema_i18n.main(["--langs", "en"]) == 0
    assert schema_i18n.main(["--check", "--langs", "en"]) == 0, "just generated = in step"


def test_the_runtime_serves_a_translation_and_falls_back(monkeypatch, tmp_path):
    """The console half: ``schema_text`` reads the generated ``.mo``, and English is the answer when
    a language has no entry."""
    babel = pytest.importorskip("babel")                        # noqa: F841 - tooling dependency
    from babel.messages.catalog import Catalog
    from babel.messages.mofile import write_mo

    directory = tmp_path / "yy" / "LC_MESSAGES"
    directory.mkdir(parents=True)
    catalog = Catalog(locale="yy", domain=i18n.SCHEMA_DOMAIN)
    catalog.add("A number.", string="EINE ZAHL")
    with (directory / "schema.mo").open("wb") as handle:
        write_mo(handle, catalog)

    monkeypatch.setattr(i18n, "LOCALE_DIR", tmp_path)
    monkeypatch.setattr(i18n, "_SCHEMA_TRANSLATORS", {})
    assert i18n.schema_text("A number.", "yy") == "EINE ZAHL"
    assert i18n.schema_text("Never translated.", "yy") == "Never translated."
    assert i18n.schema_text("A number.", "en") == "A number."
    assert i18n.schema_text("", "yy") == "", "an empty description stays empty"


